"""Score every verb in every benchmark YAML and emit a methods-section table.

Outputs
-------
- ``docs/methods/verb_frequency_table.csv`` -- one row per unique
  (benchmark, verb, tense, person, number) cell with Zipf-lemma score,
  tier, and tense-specific irregularity flag.
- ``docs/methods/verb_frequency_table.md`` -- human-readable Markdown
  grouped by benchmark, sorted by Zipf ascending. Drops straight into
  the methodology section of the dissertation.

Usage
-----
::

    python -m research.scripts.score_benchmark_verbs
"""

from __future__ import annotations

import csv
import logging
from pathlib import Path
from typing import Any

import yaml

from research.evaluation.lexicon.frequency import (
    TIER_CUTOFFS,
    is_irregular,
    tier,
    verb_zipf,
)

logging.getLogger("verbecc").setLevel(logging.WARNING)

BENCH_DIR = Path(__file__).resolve().parents[1] / "benchmarks"
OUT_DIR = Path(__file__).resolve().parents[2] / "docs" / "methods"


def _row(benchmark: str, cs: dict[str, Any], lang: str) -> dict[str, Any]:
    verb = cs["keyword"]
    tense = cs.get("tense", "") or ""
    person = cs.get("person", "") or ""
    number = cs.get("number", "") or ""

    z = verb_zipf(verb, lang)
    t = tier(verb, lang)

    if lang == "es" and tense and person and number:
        try:
            irregular = is_irregular(verb, tense, lang, person, number)
        except Exception:
            irregular = None
    else:
        irregular = None

    return {
        "benchmark": benchmark,
        "lang": lang,
        "verb": verb,
        "tense": tense,
        "person": person,
        "number": number,
        "expected_form": cs.get("expected_form", ""),
        "cefr_level": cs.get("cefr_level", ""),
        "zipf": round(z, 3),
        "tier": t,
        "irregular": "" if irregular is None else ("yes" if irregular else "no"),
    }


def _collect_rows() -> list[dict[str, Any]]:
    rows: list[dict[str, Any]] = []
    for path in sorted(BENCH_DIR.glob("*.yaml")):
        with open(path, encoding="utf-8") as f:
            data = yaml.safe_load(f)
        lang = data.get("language", "")
        bench = data.get("name", path.stem)
        for cs in data.get("constraint_sets", []) or []:
            rows.append(_row(bench, cs, lang))
    return rows


def _write_csv(rows: list[dict[str, Any]], path: Path) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    fieldnames = list(rows[0].keys())
    with open(path, "w", encoding="utf-8", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=fieldnames)
        writer.writeheader()
        writer.writerows(rows)


def _fmt_zipf(z: float) -> str:
    return f"{z:.2f}"


def _write_markdown(rows: list[dict[str, Any]], path: Path) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    lines: list[str] = []
    lines.append("# Benchmark verb frequency and irregularity")
    lines.append("")
    lines.append("Generated by `research/scripts/score_benchmark_verbs.py`.")
    lines.append("")
    lines.append(
        "Zipf-lemma scores are the log10 of per-billion frequency, summed over a "
        "canonical inflected-form set (infinitive + present indicative x6 + "
        "gerund + past participle) using `wordfreq` (Wikipedia + OpenSubtitles + "
        "news + web). Tiers are the 33rd / 67th percentiles of the Zipf-lemma "
        "distribution over a reference list of common verb infinitives per "
        "language (n=500 for Spanish, n=290 for English). Irregularity is "
        "tense-specific: `yes` means the verbecc conjugation of "
        "(verb, tense, person, number) differs from the regular-paradigm form."
    )
    lines.append("")
    lines.append("**Frozen cutoffs (Zipf-lemma):**")
    lines.append("")
    lines.append("| Language | rare < | mid | common >= |")
    lines.append("|---|---|---|---|")
    for lang, (rare_upper, common_lower) in TIER_CUTOFFS.items():
        lines.append(f"| {lang} | {_fmt_zipf(rare_upper)} | "
                     f"[{_fmt_zipf(rare_upper)}, {_fmt_zipf(common_lower)}) | "
                     f"{_fmt_zipf(common_lower)} |")
    lines.append("")

    by_bench: dict[str, list[dict[str, Any]]] = {}
    for r in rows:
        by_bench.setdefault(r["benchmark"], []).append(r)

    for bench in sorted(by_bench.keys()):
        bench_rows = sorted(by_bench[bench], key=lambda r: (r["zipf"], r["verb"]))
        lines.append(f"## `{bench}`")
        lines.append("")
        lines.append(
            "| Verb | Tense | Person/Number | Expected form | CEFR | Zipf | Tier | Irregular |"
        )
        lines.append("|---|---|---|---|---|---|---|---|")
        for r in bench_rows:
            pn = f"{r['person']} {r['number']}".strip() if r["person"] or r["number"] else ""
            lines.append(
                f"| {r['verb']} | {r['tense']} | {pn} | {r['expected_form']} | "
                f"{r['cefr_level']} | {_fmt_zipf(r['zipf'])} | {r['tier']} | "
                f"{r['irregular']} |"
            )
        lines.append("")

    path.write_text("\n".join(lines), encoding="utf-8")


def _summarise(rows: list[dict[str, Any]]) -> None:
    by_bench_tier: dict[tuple[str, str], int] = {}
    for r in rows:
        by_bench_tier[(r["benchmark"], r["tier"])] = by_bench_tier.get(
            (r["benchmark"], r["tier"]), 0
        ) + 1

    benches = sorted({r["benchmark"] for r in rows})
    print(f"{'benchmark':30s} common  mid  rare")
    for bench in benches:
        c = by_bench_tier.get((bench, "common"), 0)
        m = by_bench_tier.get((bench, "mid"), 0)
        rr = by_bench_tier.get((bench, "rare"), 0)
        print(f"{bench:30s}   {c:4d} {m:4d}  {rr:4d}")


def main() -> None:
    rows = _collect_rows()
    _write_csv(rows, OUT_DIR / "verb_frequency_table.csv")
    _write_markdown(rows, OUT_DIR / "verb_frequency_table.md")
    print(f"Wrote {len(rows)} rows to {OUT_DIR / 'verb_frequency_table.csv'}")
    print(f"Wrote Markdown table to {OUT_DIR / 'verb_frequency_table.md'}")
    print()
    _summarise(rows)


if __name__ == "__main__":
    main()
